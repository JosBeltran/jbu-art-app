import { test } from 'node:test'
import assert from 'node:assert/strict'
import { DELIVERY_DEFAULTS, deliveryConfig, isEligibleAddress, getOrderDeliveryCategory, getAvailableSlots, validateDeliverySelection } from './localDelivery.js'
const enabled = { enabled: true, paymentOnDeliveryEnabled: true }
const address = municipality => ({ country: 'MX', state: 'Nuevo León', municipality })
const slots = (time, category = 'standard', date = '2026-10-30', config = {}) => getAvailableSlots({ now: `2026-10-30T${time}:00-06:00`, category, date, config })
for (const city of ['Monterrey', 'San Nicolás de los Garza', 'Guadalupe', 'San Pedro Garza García', 'Santa Catarina', 'Apodaca', 'General Escobedo', 'García', 'Juárez']) test(`eligible ${city}`, () => assert.equal(isEligibleAddress(address(city), enabled), true))
test('enablement defaults off', () => assert.equal(isEligibleAddress(address('Monterrey')), false))
test('San Nicolas variants normalize', () => {
  for (const city of ['San Nicolas', 'San Nicolás', '  san nicolas de los garza ']) assert.equal(isEligibleAddress(address(city), enabled), true)
})
test('CDMX rejected', () => assert.equal(isEligibleAddress({ ...address('Monterrey'), state: 'CDMX' }, enabled), false))
test('international rejected', () => assert.equal(isEligibleAddress({ ...address('Monterrey'), country: 'US' }, enabled), false))
test('unknown municipality rejected', () => assert.equal(isEligibleAddress(address('Santiago'), enabled), false))
test('mixed cart uses large', () => assert.equal(getOrderDeliveryCategory([{ delivery_category: 'standard' }, { delivery_category: 'large' }]), 'large'))
test('standard cart stays standard', () => assert.equal(getOrderDeliveryCategory([{ delivery_category: 'standard' }]), 'standard'))
test('missing classification requires review', () => assert.throws(() => getOrderDeliveryCategory([{ delivery_category: null }]), /requires_review/))
test('empty cart rejected', () => assert.throws(() => getOrderDeliveryCategory([]), /empty/))
test('10 AM standard first fixed window begins 2 PM, after 1 PM minimum', () => assert.equal(slots('10:00')[0]?.startTime, '14:00'))
test('5 PM standard allows 8–10', () => assert.deepEqual(slots('17:00').map(s => [s.startTime, s.endTime]), [['20:00', '22:00']]))
test('6:30 PM no same-day slot', () => assert.equal(slots('18:30').length, 0))
test('8 PM no same-day slot', () => assert.equal(slots('20:00').length, 0))
test('late standard next day begins 10 AM', () => assert.equal(slots('20:00', 'standard', '2026-10-31')[0]?.startTime, '10:00'))
test('4:30 PM rejects 6 PM window', () => assert.deepEqual(slots('16:30').map(s => s.startTime), ['20:00']))
test('large at 10 AM no same day', () => assert.equal(slots('10:00', 'large').length, 0))
test('large at 10 AM tomorrow 10 AM', () => assert.equal(slots('10:00', 'large', '2026-10-31')[0]?.startTime, '10:00'))
test('large at 11:50 PM tomorrow 10 AM, not 24h', () => assert.equal(slots('23:50', 'large', '2026-10-31')[0]?.startTime, '10:00'))
test('all two-hour windows end at or before 22', () => assert.deepEqual(slots('00:00').map(s => s.endTime), ['12:00', '14:00', '16:00', '18:00', '20:00', '22:00']))
test('60-minute configuration uses exact 3h minimum', () => assert.equal(slots('10:00', 'standard', '2026-10-30', { slotMinutes: 60 })[0]?.startTime, '13:00'))
test('forged 11 PM selection rejected', () => assert.throws(() => validateDeliverySelection({ category: 'standard', now: '2026-10-30T10:00:00-06:00', start: '2026-10-30T23:00:00-06:00', end: '2026-10-31T01:00:00-06:00' }), /unavailable/))
test('stale selection revalidated', () => {
  const selected = slots('10:00')[0]
  assert.ok(selected)
  assert.throws(() => validateDeliverySelection({ category: 'standard', now: '2026-10-30T12:00:00-06:00', ...selected }), /unavailable/)
})
test('New York clock same instant gives Monterrey slots', () => {
  const a = getAvailableSlots({ category: 'standard', now: '2026-10-30T12:00:00-04:00', date: '2026-10-30' })
  assert.deepEqual(a, slots('10:00'))
  assert.equal(a[0]?.start, '2026-10-30T20:00:00.000Z')
})
test('offsetless clock rejected', () => assert.throws(() => getAvailableSlots({ category: 'standard', now: '2026-10-30T10:00:00', date: '2026-10-30' }), /timestamp/))
test('invalid date rejected', () => assert.throws(() => slots('10:00', 'standard', '2026-02-30'), /date/))
test('invalid hours rejected', () => assert.throws(() => deliveryConfig({ businessStart: '22:00', businessEnd: '10:00' }), /hours/))
test('large cannot allow same day', () => assert.throws(() => deliveryConfig({ largeLeadDays: 0 }), /lead/))
test('exact initial business configuration', () => {
  assert.equal(DELIVERY_DEFAULTS.timezone, 'America/Monterrey')
  assert.equal(DELIVERY_DEFAULTS.standardLeadHours, 3)
  assert.equal(DELIVERY_DEFAULTS.largeLeadDays, 1)
  assert.equal(DELIVERY_DEFAULTS.slotMinutes, 120)
})